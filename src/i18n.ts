const DICTS: Record<Lang, Dict> = { en, de, fr, pl };

// Wybór z czatu działa od razu, nawet gdy zapis do ustawień się nie uda.
let override: string | undefined;

export function setLanguageOverride(value: string | undefined): void {
  override = value;
}

export function languageSetting(): string {
  return override ?? vscode.workspace.getConfiguration("syntaxcoder").get<string>("language", "auto");
}

// "auto" = język interfejsu VS Code; nieobsługiwany język → angielski.
export function lang(): Lang {
  const set = languageSetting();
  const code = (set === "auto" ? vscode.env.language : set).slice(0, 2).toLowerCase();
  return (LANGS as readonly string[]).includes(code) ? (code as Lang) : "en";
}

export function strings(): Dict {
  return DICTS[lang()];
}

export function t(key: keyof Dict, ...args: (string | number)[]): string {
  return strings()[key].replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ""));
}
